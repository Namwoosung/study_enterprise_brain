from pathlib import Path
import json
from playwright.sync_api import sync_playwright,expect
ROOT=Path(__file__).resolve().parent;OUT=ROOT/"qa";OUT.mkdir(exist_ok=True)
checks=[];errors=[]
with sync_playwright() as p:
    browser=p.chromium.launch(headless=True)
    page=browser.new_page(viewport={"width":1440,"height":1000})
    page.on("pageerror",lambda e:errors.append(str(e)))
    def go(route):
        page.goto("http://127.0.0.1:4173/"+route)
        page.wait_for_load_state("networkidle")
    go("#/home")
    expect(page.locator(".hero .primary")).to_have_attribute("href","#/learn/c1/c1-01")
    expect(page.locator(".concept-entry")).to_be_visible()
    checks.append("first-time home starts at concepts and exposes full path")
    go("#/concepts")
    expect(page.locator("#concept-list .course-row")).to_have_count(14)
    for term in ["Enterprise Brain","Second Brain","Knowledge Graph","Ontology","Semantic Web","W3C","RDF","OWL","Property graph","Graph db","Neo4j","Cypher","SPARQL","Auto ontology","Vector rag","Graph rag","Tree rag"]:
        page.locator("#concept-filter").fill(term)
        assert page.locator("#concept-list .course-row").count()>0,term
    page.locator("#concept-filter").fill("")
    page.locator(".concept-layer").nth(1).click()
    expect(page.locator("#concept-list .course-row")).to_have_count(3)
    page.locator('.choice[data-concept-group=""]').click()
    expect(page.locator("#concept-list .course-row")).to_have_count(14)
    page.screenshot(path=str(OUT/"concepts-desktop.png"),full_page=True)
    checks.append("all requested concepts discoverable and group filters reset")
    go("#/learn/c5/c5-03")
    expect(page.locator("#representation-result")).to_contain_text("ex:RUN002")
    page.locator("#representation-mode").select_option("pg")
    expect(page.locator("#representation-result")).to_contain_text("USED_EQUIPMENT")
    page.locator("#representation-mode").select_option("context")
    expect(page.locator("#representation-result")).to_contain_text("runs.csv")
    checks.append("RDF property graph and provenance comparisons")
    go("#/learn/c11/c11-02")
    page.locator("#vector-angle").fill("90")
    expect(page.locator("#vector-angle-value")).to_have_text("90°")
    expect(page.locator(".vector-scores>div").first).to_contain_text("B")
    expect(page.locator(".vector-scores>div").first).to_contain_text("1.000")
    page.screenshot(path=str(OUT/"concept-vector-desktop.png"),full_page=True)
    checks.append("synthetic vector controls update scores and ranking")
    go("#/learn/c13/c13-03")
    expect(page.locator("#tree-strategy-result")).to_contain_text("자식")
    page.locator("#tree-strategy").select_option("collapsed")
    expect(page.locator("#tree-strategy-result")).to_contain_text("중복")
    checks.append("tree traversal and collapsed candidate explanations")
    go("#/learn/c9/c9-07")
    expect(page.locator("details.answer")).to_have_count(1)
    assert page.locator("details.answer").get_attribute("open") is None
    page.locator("#section-note").fill("같은 r 변수는 같은 작업이다.")
    page.locator("#bookmark").click()
    page.reload()
    expect(page.locator("#section-note")).to_have_value("같은 r 변수는 같은 작업이다.")
    page.locator("#toggle-done").click()
    go("#/concepts")
    expect(page.locator('#concept-list a[href="#/learn/c9/c9-01"]')).to_contain_text("1/7")
    checks.append("new lessons retain hidden answers notes bookmarks and progress")
    go("#/learn/c14/c14-06")
    page.locator("#complete-next").click()
    expect(page).to_have_url("http://127.0.0.1:4173/#/practice")
    checks.append("concept sequence ends at practice without entering another path")
    page.set_viewport_size({"width":390,"height":844})
    for route in ["#/concepts","#/learn/c5/c5-03","#/learn/c11/c11-02","#/learn/c13/c13-03"]:
        go(route)
        assert page.evaluate("document.documentElement.scrollWidth<=innerWidth+1"),route
    go("#/concepts")
    page.screenshot(path=str(OUT/"concepts-mobile.png"),full_page=True)
    checks.append("mobile concept map and interactive lessons fit viewport")
    browser.close()
assert not errors,errors
report={"passed":len(checks),"checks":checks,"errors":errors}
(OUT/"concept-report.json").write_text(json.dumps(report,ensure_ascii=False,indent=2),encoding="utf-8")
print(json.dumps(report,ensure_ascii=False))
